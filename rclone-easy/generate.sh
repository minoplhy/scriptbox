#!/usr/bin/env bash

# Treat unset variables as errors and propagate failures through pipelines
set -u
set -o pipefail

# Color codes for pretty printing
RED='\e[31m'
GREEN='\e[32m'
YELLOW='\e[33m'
CYAN='\e[36m'
NC='\e[0m' # No Color

SCRIPT_NAME="$(basename "${BASH_SOURCE[0]}")"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CONFIG_FILE="${SCRIPT_DIR}/config.txt"
OUTPUT_FILE="${SCRIPT_DIR}/run.sh"
DRY_RUN_DEFAULT=""

warn() {
    echo -e "${YELLOW}Warning: $*${NC}" >&2
}

error() {
    echo -e "${RED}Error: $*${NC}" >&2
}

# Function to print usage
usage() {
    echo -e "Usage: $0 [options]"
    echo -e "Options:"
    echo -e "  -c, --config FILE   Config file path (default: config.txt next to ${SCRIPT_NAME})"
    echo -e "  -o, --output FILE   Output script path (default: run.sh next to ${SCRIPT_NAME})"
    echo -e "  -d, --dry-run       Configure generated script to run in dry-run mode by default"
    echo -e "  -h, --help          Show this help message"
    exit "${1:-0}"
}

# Parse command line arguments
while [[ "$#" -gt 0 ]]; do
    case "$1" in
        -d|--dry-run)
            DRY_RUN_DEFAULT="--dry-run"
            shift
            ;;
        -o|--output|-c|--config)
            if [[ "$#" -lt 2 || -z "$2" ]]; then
                error "$1 requires a value"
                usage 1
            fi
            if [[ "$1" == "-o" || "$1" == "--output" ]]; then
                OUTPUT_FILE="$2"
            else
                CONFIG_FILE="$2"
            fi
            shift 2
            ;;
        -h|--help)
            usage
            ;;
        *)
            error "Unknown option: $1"
            usage 1
            ;;
    esac
done

echo -e "${CYAN}=== Rclone Sync Script Generator ===${NC}"

# Verify config file exists
if [[ ! -f "$CONFIG_FILE" ]]; then
    error "Configuration file not found at: $CONFIG_FILE"
    exit 1
fi

# Relative paths in the config resolve against the config file's directory
BASE_DIR="$(cd "$(dirname "$CONFIG_FILE")" && pwd)"

# Determine local or system rclone command statically
RCLONE_CMD="rclone"
if [[ -x "${SCRIPT_DIR}/rclone" ]]; then
    RCLONE_CMD="${SCRIPT_DIR}/rclone"
    echo -e "${YELLOW}Local rclone binary found at: ${RCLONE_CMD}. Statically writing this path to the run script.${NC}"
elif ! command -v rclone &> /dev/null; then
    warn "rclone was not found in the script directory or system PATH."
    echo -e "${YELLOW}The generated script will still attempt to use 'rclone' when run.${NC}\n" >&2
fi

# Write to a temp file first so a failed run never leaves a broken script behind
TMP_OUTPUT="$(mktemp "${OUTPUT_FILE}.XXXXXX")" || { error "Cannot write to: $OUTPUT_FILE"; exit 1; }
trap 'rm -f "$TMP_OUTPUT"' EXIT

# Strip whitespace and carriage returns; result goes to TRIMMED (avoids a subshell per line)
trim() {
    local s="${1//$'\r'/}"
    s="${s#"${s%%[![:space:]]*}"}"
    s="${s%"${s##*[![:space:]]}"}"
    TRIMMED="$s"
}

# Parse a true/false config value; result goes to BOOL_VALUE
parse_bool() {
    local key="$1" value="${2,,}"
    case "$value" in
        true|yes|1)     BOOL_VALUE="true" ;;
        false|no|0|"")  BOOL_VALUE="" ;;
        *)
            warn "Line $line_no: $key expects true/false, got '$2'. Treating as false."
            BOOL_VALUE=""
            ;;
    esac
}

# Initialize output file
{
    echo "#!/usr/bin/env bash"
    echo "# Generated by ${SCRIPT_NAME} on $(date)"
    echo "# Predefined rclone sync script"
    echo
    echo "set -u"
    echo "set -o pipefail"
    echo
    printf 'RCLONE_CMD=%q\n' "$RCLONE_CMD"
    printf 'DRY_RUN_FLAG=%q\n' "$DRY_RUN_DEFAULT"
    cat << 'EOF'

# Color codes
RED='\e[31m'
GREEN='\e[32m'
CYAN='\e[36m'
YELLOW='\e[33m'
NC='\e[0m'

echo -e "${CYAN}=== Starting Rclone Sync Jobs ===${NC}"

if [[ "${1:-}" == "--dry-run" || "${1:-}" == "-d" ]]; then
    DRY_RUN_FLAG="--dry-run"
fi

if [[ -n "$DRY_RUN_FLAG" ]]; then
    echo -e "${YELLOW}Running in DRY-RUN mode. No files will be changed.${NC}\n"
fi

# Track successes and failures
success_count=0
failure_count=0

start_block() {
    printf '\n%b>>> Starting block: %s <<<%b\n' "$CYAN" "$1" "$NC"
}

sync_folder() {
    local source_dir="$1"
    local dest_dir="$2"
    local name="$3"
    shift 3

    echo -e "\nProcessing: ${CYAN}${name}${NC}"
    echo -e "Source:      ${source_dir}"
    echo -e "Destination: ${dest_dir}"

    if [[ ! -d "$source_dir" ]]; then
        echo -e "${RED}Error: Source directory does not exist: ${source_dir}${NC}" >&2
        failure_count=$((failure_count + 1))
        return 1
    fi

    # Run rclone sync using resolved binary path and extra flags
    "$RCLONE_CMD" sync "$source_dir" "$dest_dir" -P ${DRY_RUN_FLAG:+"$DRY_RUN_FLAG"} "$@"
    local status=$?

    if [[ $status -eq 0 ]]; then
        echo -e "${GREEN}Successfully synced ${name}!${NC}"
        success_count=$((success_count + 1))
        return 0
    else
        echo -e "${RED}Error: Failed syncing ${name}. rclone status: $status${NC}" >&2
        failure_count=$((failure_count + 1))
        return $status
    fi
}
EOF
} > "$TMP_OUTPUT"

# Parse config file and append commands
blocks_processed=0
total_folders=0
declare -A seen_destinations=()

sync_block() {
    local remote="$1"
    local folders_val="$2"
    local nickname="${3:-}"
    local fast_list="${4:-}"
    local size_only="${5:-}"
    local rclone_flags="${6:-}"
    local -a folders_to_sync=()

    # Determine if folders_val points to an existing file
    local file_path="$folders_val"
    if [[ "$folders_val" != /* ]]; then
        file_path="${BASE_DIR}/$folders_val"
    fi

    if [[ -f "$file_path" ]]; then
        # Read from file line-by-line
        local f_line
        while IFS= read -r f_line || [[ -n "$f_line" ]]; do
            trim "$f_line"
            if [[ -z "$TRIMMED" || "$TRIMMED" == \#* ]]; then
                continue
            fi
            folders_to_sync+=("$TRIMMED")
        done < "$file_path"
    else
        # Fallback to inline parsing: handle JSON-like array brackets if present ["/a", "/b"]
        if [[ "$folders_val" =~ ^\[.*\]$ ]]; then
            folders_val="${folders_val#\[}"
            folders_val="${folders_val%\]}"
        fi

        # Split by comma
        local -a raw_folders
        IFS=',' read -r -a raw_folders <<< "$folders_val"

        local item
        for item in "${raw_folders[@]}"; do
            trim "$item"
            item="$TRIMMED"
            # Strip one pair of surrounding quotes
            if [[ "$item" =~ ^\"(.*)\"$ || "$item" =~ ^\'(.*)\'$ ]]; then
                item="${BASH_REMATCH[1]}"
            fi
            if [[ -n "$item" ]]; then
                folders_to_sync+=("$item")
            fi
        done
    fi

    if [[ ${#folders_to_sync[@]} -eq 0 ]]; then
        warn "No valid folders found to sync for remote '$remote'. Skipping block."
        return
    fi

    # Determine header name
    local header_name="Sync Block $((blocks_processed + 1))"
    if [[ -n "$nickname" ]]; then
        header_name="Sync Block $((blocks_processed + 1)) ($nickname)"
    fi

    # Prepare extra sync arguments
    local -a extra_sync_args=()
    if [[ "$fast_list" == "true" ]]; then
        extra_sync_args+=("--fast-list")
    fi
    if [[ "$size_only" == "true" ]]; then
        extra_sync_args+=("--size-only")
    fi
    if [[ -n "$rclone_flags" ]]; then
        # xargs splits on whitespace and honors quotes/backslashes without globbing or command substitution
        local parsed_flags
        if ! parsed_flags=$(printf '%s' "$rclone_flags" | xargs printf '%s\n' 2>/dev/null); then
            warn "Could not parse RcloneFlags for remote '$remote' (unmatched quote?): $rclone_flags. Skipping block."
            return
        fi
        local -a flags_arr=()
        mapfile -t flags_arr <<< "$parsed_flags"
        extra_sync_args+=("${flags_arr[@]}")
    fi

    # Serialize extra_sync_args for inclusion in bash script call
    local escaped_extra_args=""
    if [[ ${#extra_sync_args[@]} -gt 0 ]]; then
        escaped_extra_args=$(printf ' %q' "${extra_sync_args[@]}")
    fi

    # Strip trailing slash from remote if present
    local remote_stripped="${remote%/}"

    {
        echo
        echo "# --- ${header_name}: Remote ${remote} ---"
        printf 'start_block %q\n' "$header_name"
    } >> "$TMP_OUTPUT"

    local folder
    for folder in "${folders_to_sync[@]}"; do
        # Resolve relative paths relative to config file directory
        local resolved_folder="$folder"
        if [[ "$folder" != /* ]]; then
            resolved_folder="${BASE_DIR}/${folder}"
        fi

        # Make absolute and clean
        if [[ -d "$resolved_folder" ]]; then
            resolved_folder="$(cd "$resolved_folder" && pwd)"
        else
            warn "Source folder does not exist (yet): $resolved_folder"
        fi

        # Extract folder name for destination subdirectory
        local folder_name
        folder_name=$(basename "$resolved_folder")
        if [[ -z "$folder_name" || "$folder_name" == "/" ]]; then
            warn "Invalid folder name for path: $resolved_folder. Skipping."
            continue
        fi

        local dest_path="$remote_stripped/$folder_name"

        if [[ -n "${seen_destinations[$dest_path]:-}" ]]; then
            warn "'$resolved_folder' and '${seen_destinations[$dest_path]}' both sync to '$dest_path' and will overwrite each other."
        else
            seen_destinations[$dest_path]="$resolved_folder"
        fi

        # Append sync call to output script
        printf 'sync_folder %q %q %q%s\n' "$resolved_folder" "$dest_path" "$folder_name" "$escaped_extra_args" >> "$TMP_OUTPUT"
        ((total_folders++))
    done
    ((blocks_processed++))
}

# Parse config file line by line
current_nickname=""
current_remote=""
current_folders=""
current_fast_list=""
current_size_only=""
current_rclone_flags=""

# Helper to reset block variables
reset_block_vars() {
    current_nickname=""
    current_remote=""
    current_folders=""
    current_fast_list=""
    current_size_only=""
    current_rclone_flags=""
}

# Called when a new block starts (or at end of file): emit the pending block, or warn if it is incomplete
finish_block() {
    if [[ -n "$current_remote" && -n "$current_folders" ]]; then
        sync_block "$current_remote" "$current_folders" "$current_nickname" "$current_fast_list" "$current_size_only" "$current_rclone_flags"
    elif [[ -n "$current_remote" ]]; then
        warn "Remote '$current_remote' has no Folders. Skipping block."
    elif [[ -n "$current_folders" ]]; then
        warn "Folders '$current_folders' have no Remote. Skipping block."
    fi
    reset_block_vars
}

line_no=0
while IFS= read -r line || [[ -n "$line" ]]; do
    ((line_no++))
    trim "$line"
    line="$TRIMMED"

    if [[ -z "$line" || "$line" == \#* ]]; then
        continue
    fi

    if [[ ! "$line" =~ ^([A-Za-z]+):[[:space:]]*(.*)$ ]]; then
        warn "Line $line_no: not a 'Key: value' line, ignored: $line"
        continue
    fi
    key="${BASH_REMATCH[1],,}"
    value="${BASH_REMATCH[2]}"

    case "$key" in
        nickname)
            finish_block
            current_nickname="$value"
            ;;
        remote)
            # A Nickname given just before Remote belongs to the same block
            if [[ -n "$current_remote" || -n "$current_folders" ]]; then
                finish_block
            fi
            current_remote="$value"
            ;;
        folders)
            if [[ -n "$current_folders" ]]; then
                warn "Line $line_no: Folders given twice in one block, previous value '$current_folders' replaced."
            fi
            current_folders="$value"
            ;;
        fastlist)
            parse_bool "FastList" "$value"
            current_fast_list="$BOOL_VALUE"
            ;;
        sizeonly)
            parse_bool "SizeOnly" "$value"
            current_size_only="$BOOL_VALUE"
            ;;
        rcloneflags)
            current_rclone_flags="$value"
            ;;
        *)
            warn "Line $line_no: unknown key '${BASH_REMATCH[1]}', ignored."
            ;;
    esac
done < "$CONFIG_FILE"

# Sync the final block if ready
finish_block

if [[ $total_folders -eq 0 ]]; then
    error "No sync tasks configured in $CONFIG_FILE. Nothing generated."
    exit 1
fi

# Append final reporting block
cat << 'EOF' >> "$TMP_OUTPUT"

echo -e "${CYAN}========================================${NC}"
echo -e "Sync Job Finished."
echo -e "  Successful: ${GREEN}$success_count${NC}"
if [[ $failure_count -gt 0 ]]; then
    echo -e "  Failed/Skipped: ${RED}$failure_count${NC}"
    exit 1
else
    echo -e "  ${GREEN}All sync operations completed successfully!${NC}"
    exit 0
fi
EOF

# Make generated script executable and move it into place
# mktemp creates 0600, so restore the usual umask-based mode plus execute
chmod "$(printf '%o' $(( 0777 & ~$(umask) )))" "$TMP_OUTPUT"
mv -f "$TMP_OUTPUT" "$OUTPUT_FILE"
trap - EXIT

echo -e "${GREEN}Successfully generated executable run script at: ${OUTPUT_FILE}${NC}"
echo -e "Total blocks parsed: ${GREEN}$blocks_processed${NC}, total sync tasks configured: ${GREEN}$total_folders${NC}"
exit 0
